import Link from 'next/link';
import { useRouter } from 'next/router';
import { SignedIn } from '@clerk/nextjs';

interface SidebarProps {
  isOpen: boolean;
  onClose: () => void;
}

const sidebarLinks = [
  { href: '/dashboard', label: 'Dashboard', icon: DashboardIcon },
  { href: '/documents', label: 'Documents', icon: DocumentIcon },
  { href: '/cases', label: 'Cases', icon: CaseIcon },
  { href: '/clients', label: 'Clients', icon: ClientIcon },
  { href: '/calendar', label: 'Calendar', icon: CalendarIcon },
  { href: '/settings', label: 'Settings', icon: SettingsIcon },
];

export default function Sidebar({ isOpen, onClose }: SidebarProps) {
  const router = useRouter();

  return (
    <SignedIn>
      {/* Mobile overlay */}
      {isOpen && (
        <div
          className="fixed inset-0 bg-black/30 z-40 lg:hidden"
          onClick={onClose}
        />
      )}

      {/* Sidebar */}
      <aside
        className={`
          fixed top-16 left-0 z-40 h-[calc(100vh-4rem)] w-64 bg-white border-r border-gray-200
          transform transition-transform duration-200 ease-in-out
          ${isOpen ? 'translate-x-0' : '-translate-x-full'}
          lg:translate-x-0 lg:static lg:z-0
        `}
      >
        <nav className="mt-4 px-3 space-y-1">
          {sidebarLinks.map((link) => {
            const isActive = router.pathname === link.href || router.pathname.startsWith(link.href + '/');
            return (
              <Link
                key={link.href}
                href={link.href}
                onClick={onClose}
                className={`
                  flex items-center px-3 py-2.5 text-sm font-medium rounded-lg transition-colors
                  ${isActive
                    ? 'bg-primary-50 text-primary-700'
                    : 'text-gray-600 hover:bg-gray-50 hover:text-gray-900'
                  }
                `}
              >
                <link.icon className={`mr-3 h-5 w-5 ${isActive ? 'text-primary-600' : 'text-gray-400'}`} />
                {link.label}
              </Link>
            );
          })}
        </nav>
      </aside>
    </SignedIn>
  );
}

